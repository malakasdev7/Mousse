-- Additive adapter for the existing JSON record contract. No legacy table is removed.
create table public.audit_records (
 id bigint generated by default as identity primary key,
 store_id uuid not null references public.stores(id),
 kind text not null check(kind in ('ingredient','packaging','expense','recipe','product','sale','supplier','scenario','settings')),
 payload jsonb not null check(jsonb_typeof(payload)='object'),
 request_key uuid,
 legacy_key text,
 created_by uuid not null default auth.uid() references auth.users(id),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(store_id,request_key), unique(store_id,legacy_key)
);
create index audit_records_store_kind_idx on public.audit_records(store_id,kind,id);
alter table public.audit_records enable row level security;
revoke all on public.audit_records from anon;
grant select,insert,update,delete on public.audit_records to authenticated;
grant usage on sequence public.audit_records_id_seq to authenticated;
create policy records_read on public.audit_records for select to authenticated using(public.is_store_member(store_id));
create policy records_create on public.audit_records for insert to authenticated
 with check(public.has_store_role(store_id,array['admin','employee']::public.app_role[]) and created_by=auth.uid());
create policy records_update on public.audit_records for update to authenticated
 using(public.has_store_role(store_id,array['admin','employee']::public.app_role[]))
 with check(public.has_store_role(store_id,array['admin','employee']::public.app_role[]));
create policy records_delete on public.audit_records for delete to authenticated
 using(public.has_store_role(store_id,array['admin']::public.app_role[]));

